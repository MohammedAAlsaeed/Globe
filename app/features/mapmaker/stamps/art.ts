/**
 * Vector stamp art: how the built-in stamps are drawn.
 *
 * Every built-in stamp is a small drawing made of *parts*, each painted in
 * one of the stamp's two colors:
 *
 *   fill   the body (a mountain's face, a tree's foliage, a house's walls)
 *   shade  the side away from the light — the fill, darkened toward the ink
 *   light  highlights (snow caps, sunlit sails) — the fill, lightened
 *   ink    outlines and hatching, stroked
 *   solid  small solid details (doors, windows, trunks), filled with ink
 *
 * So a person recolors a whole stamp with just two colors (ink and fill),
 * and Hue / Saturation / Brightness / Contrast act on those colors exactly.
 *
 * Art is generated by small seeded functions (see ./builtin), drawn with a
 * slightly wobbly `Pen` for a hand-inked look. The Pen tracks the drawing's
 * bounds, and `finish()` moves the drawing to a tight box at (0, 0), so a
 * stamp's selection box always hugs what you see.
 */
import { mulberry32 } from "../brush/noise";

export type PartRole = "fill" | "shade" | "light" | "ink" | "solid";
export interface ArtPart {
  role: PartRole;
  /** SVG path data, in art units (the art's box is w × h). */
  d: string;
  /** Ink parts: stroke width in art units. */
  width?: number;
}
export interface VectorArt {
  w: number;
  h: number;
  parts: ArtPart[];
}

type Cmd =
  | { op: "M" | "L"; x: number; y: number }
  | { op: "Q"; cx: number; cy: number; x: number; y: number }
  | { op: "Z" };
interface RawPart {
  role: PartRole;
  cmds: Cmd[];
  width?: number;
}
export type Pt = [number, number];

/** Draws a stamp with a seeded, slightly unsteady hand. */
export class Pen {
  readonly rand: () => number;
  private parts: RawPart[] = [];
  private minX = Infinity;
  private minY = Infinity;
  private maxX = -Infinity;
  private maxY = -Infinity;
  /** Default ink width, art units. */
  ink = 1.6;

  constructor(seed: number) {
    this.rand = mulberry32(seed * 7919 + 13);
  }
  /** A random number in [a, b). */
  r(a: number, b: number) {
    return a + (b - a) * this.rand();
  }
  /** Points along a straight line with a small random wobble (hand-drawn). */
  wobble(from: Pt, to: Pt, steps: number, amount: number): Pt[] {
    const out: Pt[] = [],
      dx = to[0] - from[0],
      dy = to[1] - from[1],
      len = Math.hypot(dx, dy) || 1,
      nx = -dy / len,
      ny = dx / len;
    for (let i = 0; i <= steps; i++) {
      const t = i / steps,
        k = i === 0 || i === steps ? 0 : this.r(-amount, amount);
      out.push([from[0] + dx * t + nx * k, from[1] + dy * t + ny * k]);
    }
    return out;
  }
  /** Points around an ellipse, with a random radial wobble (blobs, canopies). */
  blob(
    cx: number,
    cy: number,
    rx: number,
    ry: number,
    n: number,
    wobble: number,
    start = 0,
  ): Pt[] {
    const out: Pt[] = [];
    for (let i = 0; i < n; i++) {
      const a = start + (i / n) * Math.PI * 2,
        k = 1 + this.r(-wobble, wobble);
      out.push([cx + Math.cos(a) * rx * k, cy + Math.sin(a) * ry * k]);
    }
    return out;
  }
  /** A filled shape. `smooth` rounds the corners through quadratic curves. */
  shape(role: Exclude<PartRole, "ink">, pts: Pt[], smooth = false) {
    this.add({ role, cmds: toCmds(pts, true, smooth) });
  }
  /** An ink line (open unless `closed`). */
  line(
    pts: Pt[],
    opts: { width?: number; closed?: boolean; smooth?: boolean } = {},
  ) {
    this.add({
      role: "ink",
      cmds: toCmds(pts, !!opts.closed, !!opts.smooth),
      width: opts.width ?? this.ink,
    });
  }
  /** A filled shape outlined in ink — the most common stamp part. */
  inked(
    role: Exclude<PartRole, "ink">,
    pts: Pt[],
    smooth = false,
    width?: number,
  ) {
    this.shape(role, pts, smooth);
    this.line(pts, { closed: true, smooth, width });
  }
  /** A filled circle (solid details, smoke puffs). */
  dot(role: Exclude<PartRole, "ink">, cx: number, cy: number, r: number) {
    this.shape(role, this.blob(cx, cy, r, r, 10, 0), true);
  }

  private add(part: RawPart) {
    const pad = (part.width ?? 0) / 2;
    for (const c of part.cmds) {
      if (c.op === "Z") continue;
      const xs = c.op === "Q" ? [c.cx, c.x] : [c.x],
        ys = c.op === "Q" ? [c.cy, c.y] : [c.y];
      for (const x of xs) {
        this.minX = Math.min(this.minX, x - pad);
        this.maxX = Math.max(this.maxX, x + pad);
      }
      for (const y of ys) {
        this.minY = Math.min(this.minY, y - pad);
        this.maxY = Math.max(this.maxY, y + pad);
      }
    }
    this.parts.push(part);
  }

  /** The finished art, moved to a tight box at (0, 0). */
  finish(): VectorArt {
    const ox = this.minX,
      oy = this.minY,
      f = (v: number) => Math.round(v * 100) / 100;
    return {
      w: f(this.maxX - ox),
      h: f(this.maxY - oy),
      parts: this.parts.map((p) => ({
        role: p.role,
        width: p.width,
        d: p.cmds
          .map((c) =>
            c.op === "Z"
              ? "Z"
              : c.op === "Q"
                ? `Q${f(c.cx - ox)} ${f(c.cy - oy)} ${f(c.x - ox)} ${f(c.y - oy)}`
                : `${c.op}${f(c.x - ox)} ${f(c.y - oy)}`,
          )
          .join(""),
      })),
    };
  }
}

/** Polyline → commands. Smooth paths pass through the midpoints of each
 * segment, using the points themselves as quadratic control points. */
function toCmds(pts: Pt[], closed: boolean, smooth: boolean): Cmd[] {
  if (pts.length === 0) return [];
  if (!smooth || pts.length < 3) {
    const cmds: Cmd[] = pts.map(([x, y], i) => ({
      op: i === 0 ? "M" : "L",
      x,
      y,
    }));
    if (closed) cmds.push({ op: "Z" });
    return cmds;
  }
  const mid = (a: Pt, b: Pt): Pt => [(a[0] + b[0]) / 2, (a[1] + b[1]) / 2];
  const cmds: Cmd[] = [];
  if (closed) {
    const n = pts.length,
      start = mid(pts[n - 1], pts[0]);
    cmds.push({ op: "M", x: start[0], y: start[1] });
    for (let i = 0; i < n; i++) {
      const p = pts[i],
        m = mid(p, pts[(i + 1) % n]);
      cmds.push({ op: "Q", cx: p[0], cy: p[1], x: m[0], y: m[1] });
    }
    cmds.push({ op: "Z" });
    return cmds;
  }
  cmds.push({ op: "M", x: pts[0][0], y: pts[0][1] });
  for (let i = 1; i < pts.length - 1; i++) {
    const m = mid(pts[i], pts[i + 1]);
    cmds.push({ op: "Q", cx: pts[i][0], cy: pts[i][1], x: m[0], y: m[1] });
  }
  const last = pts[pts.length - 1];
  cmds.push({ op: "L", x: last[0], y: last[1] });
  return cmds;
}
